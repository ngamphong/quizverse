// Generates supabase/seed.sql from lib/sampleQuiz.ts so the database sample room
// always matches the code. Run: node scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { SAMPLE_QUIZ } from "../lib/sampleQuiz.ts";

const s = (v: string) => "'" + v.replace(/'/g, "''") + "'";
const rows = SAMPLE_QUIZ.questions.map((q, i) =>
  `    (qid, ${i}, ${s(q.topic)}, ${q.level}, ${s(q.q)}, ${s(JSON.stringify(q.choices))}::jsonb, ${q.answer}, ${s(q.explain)})`,
);

const sql = `-- QUIZVERSE sample room (PIN ${SAMPLE_QUIZ.pin}). Generated by scripts/gen-seed.ts — do not edit by hand.
-- Run after schema.sql. Safe to run again: it skips if the room already exists.
do $$
declare qid uuid;
begin
  if not exists (select 1 from public.quizzes where pin = ${s(SAMPLE_QUIZ.pin)}) then
    insert into public.quizzes (pin, title, is_sample)
    values (${s(SAMPLE_QUIZ.pin)}, ${s(SAMPLE_QUIZ.title)}, true)
    returning id into qid;

    insert into public.questions (quiz_id, position, topic, level, q, choices, answer, explain) values
${rows.join(",\n")};
  end if;
end $$;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql, "utf8");
console.log(`wrote supabase/seed.sql (${SAMPLE_QUIZ.questions.length} questions)`);
